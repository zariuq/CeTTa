#!/bin/sh
# The global names of a compiled module's instance (one translation unit: the rule runtime, the
# components, the generated code and the host glue), each given the instance's prefix, so that
# several compiled modules link into one binary, each with its own store.
#
#   sh tools/rulec/instance_names.sh INSTANCE.c NAMES.h PREFIX KEPT [CC FLAGS...]
#
# INSTANCE.c includes NAMES.h first.  The instance is compiled with an empty NAMES.h; every global
# name it defines except those of KEPT (its exported names, separated by spaces: a dispatch function,
# a table, an API) gets PREFIX (NAMES.h is written); it is compiled again and must define no global
# name outside PREFIX but the kept ones.
set -eu
INST=$1; NAMES=$2; PREFIX=$3; KEPT=" $4 "; shift 4
OBJ=$NAMES.probe.o
trap 'rm -f "$OBJ" "$NAMES.new"' EXIT INT TERM
: > "$NAMES"
${CC:-cc} "$@" -c "$INST" -o "$OBJ"
{
  printf '/* Generated by tools/rulec/instance_names.sh: the global names of this module instance, prefixed\n'
  printf ' * so that it links beside other compiled modules; do not edit. */\n'
  nm -g --defined-only "$OBJ" | awk -v k="$KEPT" -v p="$PREFIX" 'index(k, " " $3 " ") == 0 { print "#define " $3 " " p $3 }' | sort
} > "$NAMES.new"
mv "$NAMES.new" "$NAMES"
${CC:-cc} "$@" -c "$INST" -o "$OBJ"
LEFT=$(nm -g --defined-only "$OBJ" | awk -v k="$KEPT" -v p="$PREFIX" 'index(k, " " $3 " ") == 0 && index($3, p) != 1' | wc -l)
if [ "$LEFT" != 0 ]; then echo "instance_names.sh: $INST defines $LEFT global names outside $PREFIX" >&2; exit 1; fi
echo "$(grep -c '^#define' "$NAMES") instance names with prefix $PREFIX"
