#!/bin/sh
# Regenerate native/hol_light_module/generated/ from the HOL Light kernel module.
#
#   sh tools/rulec/regen_hol_light_module.sh MODULE-FILE [CETTA-BINARY]
#
# MODULE-FILE is the HOL Light kernel module, kept in Mettapedia as
# metta/gslt/module/HOLLightKernel.module; for example, from the CeTTa root:
#
#   sh tools/rulec/regen_hol_light_module.sh <Mettapedia checkout>/metta/gslt/module/HOLLightKernel.module
#
# CeTTa's own module reader prints the module's core rows (tools/rulec/dump_wire.metta); rulec
# (tools/rulec/compiler) compiles them (census, decision DAGs, C); rulec_validate checks every DAG
# against the rules and the generated dispatch code against the DAGs.  Any failure stops before
# generated/ changes.  The representations of the sorts and the components that answer judgments are
# the rows of native/hol_light_module/hol.bindings (see docs/rulec.txt).  Then the instance's names
# (tools/rulec/instance_names.sh): every global name of hlm_instance.c but cetta_holm_dispatch gets
# the prefix hlm_ (generated/hol_instance_names.h); the instance reads streams through the HOLR reader's
# table (native/holr_reader_module, regenerated by regen_holr_reader_module.sh), fed to the module as
# hlm_feed.c describes.  Everything is made in a staging copy.
set -eu
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
MODULE=$(cd "$(dirname "$1")" && pwd)/$(basename "$1")
CETTA=${2:-$ROOT/cetta}
WORK=$ROOT/runtime/rulec
STAGE=$WORK/stage
GEN=$ROOT/native/hol_light_module/generated
SG=$STAGE/native/hol_light_module/generated
rm -rf "$STAGE"
mkdir -p "$WORK" "$GEN" "$SG"
CC=${CC:-cc}
$CC -O2 -o "$WORK/rulec" "$ROOT"/tools/rulec/compiler/*.c
$CC -O2 -o "$WORK/rulec_validate" "$ROOT/tools/rulec/rulec_validate.c"
$CC -O2 -o "$WORK/rulec_tracecheck" "$ROOT/tools/rulec/rulec_tracecheck.c"
printf '!(import! &self "%s")\n!(wire:dump "%s" "Kernel")\n' "$ROOT/tools/rulec/dump_wire.metta" "$MODULE" > "$WORK/dump.metta"
"$CETTA" "$WORK/dump.metta" | grep '^(' > "$WORK/HOLLightKernel.wire"
SHA=$(sha256sum "$MODULE" | cut -d' ' -f1)
"$WORK/rulec" "$WORK/HOLLightKernel.wire" \
  --layers data=not-yes,syntax=bool-ty,kernel=type-of-var,rules=REFL,theory=initial-theory,replay=policy-max-open \
  --census "$WORK/census.txt" --census-tsv "$WORK/census.tsv" --dag "$WORK/HOLLightKernel.dag" \
  --safepoint hl:run --cache-constants --bindings "$ROOT/native/hol_light_module/hol.bindings" \
  --include-rt ../../rule_runtime/rc_rt.h --component-prefix ../../rule_components/ --source-digest "$SHA" \
  --emit "$SG/hol_module.c" --emit-h "$SG/hol_module_ids.h"
"$WORK/rulec_validate" "$WORK/HOLLightKernel.wire" "$WORK/HOLLightKernel.dag" "$SG/hol_module.c"
cp -r "$ROOT/native/rule_runtime" "$ROOT/native/rule_components" "$ROOT/native/rule_module" "$ROOT/native/hol_light" "$STAGE/native/"
cp "$ROOT/native/hol_light_module/hlm_instance.c" "$ROOT/native/hol_light_module/hlm_feed.c" \
   "$ROOT/native/hol_light_module/holm_cetta_module.h" "$STAGE/native/hol_light_module/"
sh "$ROOT/tools/rulec/instance_names.sh" "$STAGE/native/hol_light_module/hlm_instance.c" "$SG/hol_instance_names.h" hlm_ cetta_holm_dispatch \
  -std=c11 -pthread -I"$ROOT/src" -I"$ROOT"
cp "$SG/hol_module.c" "$SG/hol_module_ids.h" "$SG/hol_instance_names.h" "$WORK/HOLLightKernel.dag" "$WORK/census.txt" "$GEN/"
rm -rf "$STAGE"
echo "regenerated $GEN from module SHA-256 $SHA"
