#!/usr/bin/env python3
"""Python 3.15's builtin types, as a table of the Python complex.

    python_builtin_types_v1.py OUTPUT [--check]

Writes langdef/python/builtin_types.metta from the running CPython's own
types: every type in the builtins module (the exception hierarchy among
them) and the types of the core's other built-in values (None, functions,
methods, cells, iterators, dict views, ...).  Each row gives a type's name,
module, bases, method resolution order, whether it may be subclassed and
whether its instances have a __dict__; the types of the core's typing
objects (generic aliases, unions, type parameters and type aliases) and of
template strings (string.templatelib's) are among them, each with its own
module.
The names in builtins that are aliases (IOError is OSError) are rows of
their own kind.  The struct sequences the runtime makes (sys.version_info,
os.stat_result, ...) are rows too, with their fields; so are the types
whose instances cannot be made by calling them.  With --check the file must
equal a fresh generation.
"""
import _string
import builtins
import os
import posix
import sys
import types
import typing
from string.templatelib import Interpolation, Template

# the iterators of the _string module's str.format parser
FORMATTER_ITERATOR = type(_string.formatter_parser(""))
FIELD_NAME_ITERATOR = type(_string.formatter_field_name_split("")[1])
# a lazy import's placeholder (types.LazyImportType); made, not resolved
_LAZY_GLOBALS = {}
exec("lazy import json", _LAZY_GLOBALS)
LAZY_IMPORT = type(_LAZY_GLOBALS["json"])

ROW_HEADER = """; Python 3.15's builtin types (generated by tools/python_builtin_types_v1.py
; from CPython 3.15; do not edit).  A builtin type is (py:type NAME):
;   (pyrt:btype NAME) = (bt NAME-STRING MODULE (BASES ...) (MRO ...) SUBCLASSABLE HAS-DICT)
; HAS-DICT: whether its instances have a __dict__ (CPython's tp_dictoffset)
;   (pyrt:builtin-type-name STRING) = NAME, for the names in builtins
"""

EXTRA = [
    type(None), type(NotImplemented), type(Ellipsis),
    types.FunctionType, types.BuiltinFunctionType, types.MethodType, types.CellType,
    types.CodeType, types.ModuleType, types.GeneratorType, types.MappingProxyType,
    type(iter([])), type(reversed([])), type(iter(range(0))), type(iter(())),
    type(iter("")), type(iter("é")), type(iter(set())), type(iter({})),
    type(iter({}.values())), type(iter({}.items())),
    type({}.keys()), type({}.values()), type({}.items()),
    types.GetSetDescriptorType, types.MemberDescriptorType, types.WrapperDescriptorType,
    types.MethodWrapperType, types.MethodDescriptorType, types.ClassMethodDescriptorType,
    types.FrameType, types.TracebackType, types.CoroutineType, types.AsyncGeneratorType,
    type(iter(zip())), type(enumerate([])), type(reversed(range(0))), type(iter(bytearray())), type(iter(b"")),
    type(iter(type("Items", (), {"__getitem__": lambda self, i: 0})())),
    types.GenericAlias, types.UnionType,
    typing.TypeVar, typing.ParamSpec, typing.ParamSpecArgs, typing.ParamSpecKwargs,
    typing.TypeVarTuple, typing.TypeAliasType, typing.Generic, type(typing.NoDefault),
    Template, Interpolation, type(iter(Template())), FORMATTER_ITERATOR, FIELD_NAME_ITERATOR,
    LAZY_IMPORT, types.SimpleNamespace, types.CapsuleType,
]

# the struct sequences (Objects/structseq.c) the runtime makes
STRUCTSEQ_TYPES = [
    type(sys.version_info), type(sys.flags), type(sys.float_info), type(sys.int_info), type(sys.hash_info),
    os.stat_result, os.terminal_size, posix.uname_result,
]
EXTRA += STRUCTSEQ_TYPES


def builtin_types():
    seen, out = set(), []
    for name, value in vars(builtins).items():
        if isinstance(value, type) and value.__module__ == "builtins" and value not in seen:
            seen.add(value)
            out.append(value)
    for t in EXTRA:
        if t not in seen:
            seen.add(t)
            out.append(t)
    return out


def sym(t):
    return t.__name__


def render():
    if sys.version_info[:2] != (3, 15):
        raise SystemExit("needs CPython 3.15, not %d.%d" % sys.version_info[:2])
    tys = builtin_types()
    lines = [ROW_HEADER]
    for t in tys:
        bases = " ".join("(py:type %s)" % sym(b) for b in t.__bases__)
        mro = " ".join("(py:type %s)" % sym(m) for m in t.__mro__)
        sub = "True" if t.__flags__ & (1 << 10) else "False"
        has_dict = "True" if t.__dictoffset__ != 0 else "False"
        lines.append('(= (pyrt:btype %s) (bt "%s" "%s" (%s) (%s) %s %s))'
                     % (sym(t), t.__name__, t.__module__, bases, mro, sub, has_dict))
    lines.append("")
    names = sorted((k, v) for k, v in vars(builtins).items()
                   if isinstance(v, type) and v.__module__ == "builtins")
    lines.append("(= (pyrt:builtin-type-name $n)")
    lines.append("   (case $n")
    entries = ['("%s" %s)' % (k, sym(v)) for k, v in names]
    for i in range(0, len(entries), 4):
        lead = "     (" if i == 0 else "      "
        lines.append(lead + " ".join(entries[i:i + 4]))
    lines.append("      ($other (m:missing)))))")
    lines.append("")
    lines.append(MEMBER_HEADER)
    for t in MEMBER_TYPES:
        for name, v in vars(t).items():
            kind = member_kind(name, v)
            if kind is not None:
                lines.append('(pyrt:bmember %s "%s" %s)' % (sym(t), name, kind))
    lines.append("")
    lines.append(LAYOUT_HEADER)
    check_layouts(tys)
    for t in tys:
        lines.append("(pyrt:blayout %s (py:type %s) %s %s)"
                     % (sym(t), sym(solid_base(t)), "True" if t.__itemsize__ else "False",
                        "True" if t.__weakrefoffset__ else "False"))
    lines.append("")
    lines.append(DOC_HEADER)
    for t in MEMBER_TYPES:
        doc = vars(t).get("__doc__")
        if isinstance(doc, str):
            lines.append('(pyrt:bdoc %s "%s")' % (sym(t), metta_text(doc)))
    lines.append("")
    lines.append(STRUCTSEQ_HEADER)
    for t in STRUCTSEQ_TYPES:
        visible, unnamed, fields = structseq_layout(t)
        lines.append("(pyrt:bstructseq %s %d %d (%s))" % (sym(t), visible, unnamed, " ".join(
            '("%s" "%s")' % (name, metta_text(doc)) for name, doc in fields)))
    lines.append("")
    lines.append(NOINSTANCES_HEADER)
    for t in tys:
        if t.__flags__ & DISALLOW_INSTANTIATION:
            lines.append("(pyrt:bnoinstances %s)" % sym(t))
    return "\n".join(lines) + "\n"


DISALLOW_INSTANTIATION = 1 << 7

STRUCTSEQ_HEADER = """; the struct sequences (Objects/structseq.c): (pyrt:bstructseq TYPE VISIBLE
; UNNAMED ((NAME DOC) ...)): a tuple of VISIBLE items, its last UNNAMED of
; them without a name, and the named fields in their order (tp_members),
; each with its member's doc: those of the tuple's named items first, then
; the fields beyond the tuple"""

NOINSTANCES_HEADER = """; the types whose instances calling them does not make
; (Py_TPFLAGS_DISALLOW_INSTANTIATION, tp_new NULL: "cannot create 'T' instances")"""


def structseq_layout(t):
    # structseq.c keeps a struct sequence's fields in one array: the named
    # items of the tuple, its unnamed ones (the end of the tuple), then the
    # fields beyond it; checked against what CPython's own instances hold
    d = vars(t)
    names = [k for k, v in d.items() if type(v) is types.MemberDescriptorType]
    visible, total, unnamed = d["n_sequence_fields"], d["n_fields"], d["n_unnamed_fields"]
    named_visible = visible - unnamed
    if len(names) + unnamed != total or tuple(names[:named_visible]) != t.__match_args__:
        raise SystemExit("struct sequence %s: members and counts disagree" % t.__name__)
    positions = list(range(named_visible)) + list(range(visible, total))
    if "__new__" in d:
        sample = t(range(total))
        for name, pos in zip(names, positions):
            if getattr(sample, name) != pos:
                raise SystemExit("struct sequence %s: %s is not item %d" % (t.__name__, name, pos))
    else:
        sample = {type(sys.version_info): sys.version_info, type(sys.flags): sys.flags}[t]
    items, beyond = sample.__reduce__()[1]
    if len(items) != visible or tuple(beyond) != tuple(names[named_visible:]):
        raise SystemExit("struct sequence %s: the fields beyond the tuple are not in member order" % t.__name__)
    return visible, unnamed, [(name, getattr(t, name).__doc__ or "") for name in names]


HEAPTYPE = 1 << 9
POINTER = 8


def extra_ivars(t, base):
    # typeobject.c extra_ivars: whether T's instances hold more than BASE's
    t_size, b_size = t.__basicsize__, base.__basicsize__
    if t.__itemsize__ or base.__itemsize__:
        return t_size != b_size or t.__itemsize__ != base.__itemsize__
    if t.__flags__ & HEAPTYPE:
        if (t.__weakrefoffset__ and base.__weakrefoffset__ == 0
                and t.__weakrefoffset__ + POINTER == t_size):
            t_size -= POINTER
        if (t.__dictoffset__ > 0 and base.__dictoffset__ == 0
                and t.__dictoffset__ + POINTER == t_size):
            t_size -= POINTER
    return t_size != b_size


def solid_base(t):
    # typeobject.c solid_base: the most derived class whose instance layout
    # adds to its base's
    base = solid_base(t.__base__) if t.__base__ is not None else object
    return t if extra_ivars(t, base) else base


def check_layouts(tys):
    # the rows must say what CPython does: two subclassable types conflict
    # (best_base) exactly when neither solid base is a subclass of the other
    subs = [t for t in tys if t.__flags__ & (1 << 10)]
    for a in subs:
        for b in subs:
            if a is b:
                continue
            sa, sb = solid_base(a), solid_base(b)
            predicted = not (issubclass(sa, sb) or issubclass(sb, sa))
            try:
                type("Probe", (a, b), {})
                conflict = False
            except TypeError as e:
                conflict = "lay-out conflict" in str(e)
            if conflict != predicted:
                raise SystemExit("solid base of %s or %s disagrees with CPython" % (a.__name__, b.__name__))


LAYOUT_HEADER = """; their instance layouts: (pyrt:blayout TYPE SOLID VARSIZE WEAKREF), SOLID the
; class solid_base gives (typeobject.c: the most derived class whose instances
; hold more than its base's), VARSIZE whether its instances have items of
; their own (tp_itemsize: no nonempty __slots__ below it), WEAKREF whether
; they take weak references (tp_weaklistoffset)"""


def metta_text(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


DOC_HEADER = """; their docstrings, the __doc__ of their namespaces"""


MEMBER_HEADER = """; The members of the core builtin types' own namespaces, as CPython 3.15 has
; them: (pyrt:bmember TYPE NAME KIND), KIND one of method (a method
; descriptor), slot (a slot wrapper: a dunder its slot implements), classmethod,
; static, new (tp_new as __new__), getset, member, or unhashable (__hash__ None)"""

MEMBER_TYPES = [object, type, int, bool, float, complex, str, bytes, bytearray, list, tuple, dict,
                set, frozenset, range, slice, Template, Interpolation, type(iter(Template())),
                FORMATTER_ITERATOR, FIELD_NAME_ITERATOR, LAZY_IMPORT, types.SimpleNamespace, staticmethod, classmethod,
                *STRUCTSEQ_TYPES]


def member_kind(name, v):
    kind = type(v).__name__
    if kind == "method_descriptor":
        return "method"
    if kind == "wrapper_descriptor":
        return "slot"
    if kind == "classmethod_descriptor":
        return "classmethod"
    if kind == "staticmethod":
        return "static"
    if kind == "builtin_function_or_method" and name == "__new__":
        return "new"
    if kind == "getset_descriptor":
        return "getset"
    if kind == "member_descriptor":
        return "member"
    if v is None and name == "__hash__":
        return "unhashable"
    return None


def main(argv):
    if len(argv) < 2 or argv[1].startswith("-"):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    out = argv[1]
    text = render()
    if "--check" in argv[2:]:
        try:
            current = open(out, encoding="utf-8").read()
        except FileNotFoundError:
            current = None
        if current != text:
            print("%s is out of date with CPython %s" % (out, sys.version.split()[0]), file=sys.stderr)
            return 1
        print("%s is up to date" % out)
        return 0
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
