#!/usr/bin/env python3
"""Writes the GSLT presentations of Megalodon's syntax, langdef/megalodon/:
the lexer (lexical_v1) and the parser's presentations (notation_environment_v1,
term_parser_v1, document_v1, proof_script_v1, source_fold_v1), from the
programs in tools/megalodon_gslt.  With --check, compares instead of writing
and fails when a presentation differs from what this program generates."""

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from megalodon_gslt import lexical, parser  # noqa: E402

GENERATED = ('; Generated by tools/generate_megalodon_gslt_v1.py from '
             'tools/megalodon_gslt; regenerate rather than edit.\n')


def presentations():
    files = {'lexical_v1.metta': lexical.generate()}
    files.update(parser.generate())
    return {name: GENERATED + text for name, text in files.items()}


def main():
    arguments = argparse.ArgumentParser(description=__doc__)
    arguments.add_argument('--out', default='langdef/megalodon')
    arguments.add_argument('--check', action='store_true')
    args = arguments.parse_args()
    out = pathlib.Path(args.out)
    stale = []
    for name, text in sorted(presentations().items()):
        path = out / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print('stale Megalodon presentations: ' + ' '.join(stale), file=sys.stderr)
        return 1
    print('(MegalodonGsltPresentations %d %s)' % (len(presentations()), 'checked' if args.check else 'written'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
