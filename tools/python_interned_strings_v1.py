#!/usr/bin/env python3
"""The strings CPython 3.15 holds interned once it has started, as a table of
the Python complex.

    python_interned_strings_v1.py OUTPUT [--source DIR] [--check]

Writes langdef/python/interned_strings.metta: the strings of two or more
ASCII letters, digits and underscores that CPython holds interned when it has
started as the run gate starts it (-s -P, with PYTHONHASHSEED=0 its only
environment).  When a code object is made, a frozenset constant holding a
string equal to an interned one (another object) is built again
(codeobject.c intern_constants), and that decides the order the set display
it came from iterates in.

The candidates are the words of the CPython sources given with --source (its
Lib, Objects, Python, Modules, Include and Parser: the frozen modules that run
at start-up are only there), the words of the installed standard library,
and every string a started interpreter reaches (the names of its modules,
types and functions, and the strings its dicts, lists and tuples hold).  A
fresh interpreter started as the gate starts it tests each one: sys.intern(t)
is not t when an equal string was interned before.  With --check the file
must equal a fresh generation.
"""
import gc
import os
import re
import subprocess
import sys
import sysconfig
import tempfile
import types

HEADER = """; The strings Python 3.15 holds interned once it has started as the run gate
; starts it (generated by tools/python_interned_strings_v1.py from CPython
; 3.15; do not edit): those of two or more ASCII letters, digits and
; underscores.  A frozenset constant holding a string equal to one of them is
; built again when its code object is made (codeobject.c intern_constants).
"""

WORD = re.compile(r"[A-Za-z0-9_]{2,}")
SOURCE_DIRS = ("Lib", "Objects", "Python", "Modules", "Include", "Parser")
SOURCE_SUFFIXES = (".py", ".c", ".h")

# reads the candidates, one per line, and writes those an equal string of
# was interned before; its own names are interned when it starts
PROBE = """import sys
for t in sys.stdin.read().split():
    if sys.intern(t) is not t:
        print(t)
"""


def words_of_tree(root, suffixes):
    found = set()
    for d, dirs, files in os.walk(root):
        dirs.sort()
        for f in sorted(files):
            if f.endswith(suffixes):
                try:
                    with open(os.path.join(d, f), encoding="utf-8", errors="replace") as fh:
                        found.update(WORD.findall(fh.read()))
                except OSError:
                    pass
    return found


def reachable_strings():
    found = set()
    for o in gc.get_objects():
        if isinstance(o, (type, types.ModuleType)):
            try:
                found.update(n for n in dir(o) if isinstance(n, str))
            except Exception:
                pass
        if isinstance(o, dict):
            for k, v in list(o.items()):
                if isinstance(k, str):
                    found.add(k)
                if isinstance(v, str):
                    found.add(v)
        elif isinstance(o, (list, tuple)):
            found.update(x for x in o if isinstance(x, str))
        co = getattr(o, "__code__", None)
        if isinstance(co, types.CodeType):
            found.update(co.co_names + co.co_varnames + co.co_freevars + co.co_cellvars)
            found.update(c for c in co.co_consts if isinstance(c, str))
    found.update(sys.builtin_module_names)
    found.update(sys.modules)
    return found


def candidates(source):
    found = set()
    if source:
        for d in SOURCE_DIRS:
            found |= words_of_tree(os.path.join(source, d), SOURCE_SUFFIXES)
    found |= words_of_tree(sysconfig.get_paths()["stdlib"], (".py",))
    found |= reachable_strings()
    return sorted(s for s in found if WORD.fullmatch(s))


def interned(cands):
    with tempfile.TemporaryDirectory() as d:
        probe = os.path.join(d, "probe.py")
        with open(probe, "w") as fh:
            fh.write(PROBE)
        out = subprocess.run([sys.executable, "-s", "-P", probe], input="\n".join(cands) + "\n",
                             capture_output=True, text=True, env={"PYTHONHASHSEED": "0"}, cwd=d, check=True)
    return sorted(set(out.stdout.split()))


def table(source):
    if sys.version_info[:2] != (3, 15):
        raise SystemExit("needs CPython 3.15, not %d.%d" % sys.version_info[:2])
    rows = ['(py:interned "%s")' % s for s in interned(candidates(source))]
    return HEADER + "\n".join(rows) + "\n"


def main(argv):
    if len(argv) < 2 or argv[1].startswith("-"):
        print(__doc__, file=sys.stderr)
        return 2
    out = argv[1]
    rest = argv[2:]
    source = None
    if "--source" in rest:
        i = rest.index("--source")
        if i + 1 >= len(rest):
            print("--source needs a directory", file=sys.stderr)
            return 2
        source = rest[i + 1]
    text = table(source)
    if "--check" in rest:
        with open(out) as fh:
            if fh.read() != text:
                print("FAIL: %s differs from a fresh generation" % out, file=sys.stderr)
                return 1
        print("PASS: %s" % out)
        return 0
    with open(out, "w") as fh:
        fh.write(text)
    print("wrote %s (%d strings)" % (out, text.count("(py:interned ")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
