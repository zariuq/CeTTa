#!/usr/bin/env python3
"""Generate the Megalodon elaboration tables from upstream source.

Reads Megalodon's src/syntax.ml and src/megalodon.ml and writes
native/megalodon/mg_upstream_tables.inc:

  * the Proofgold primitive of each theory's Megalodon identities
    (syntax.ml pfghfprim, pfgegalprim, pfgmizprim, pfghoasprim,
    pfgsetmmprim), which the Proofgold translation of a term consults
    before the pure roots of its definitions;
  * the preset hash indexes (megalodon.ml preset_hf_index,
    preset_mizar_index, preset_hoas_index, preset_setmm_index): the types
    Megalodon knows for identities before any document is read (indextms)
    and the propositions it knows (indexknowns);
  * the named constants of the distinct tactic (megalodon.ml), the knowns
    and terms its proofs are built from.

Megalodon calls preset_mizar_index before reading its options, and -hf adds
preset_hf_index to it without clearing, while -mizar, -hoas and -setmm
clear first; the tables record each function's own rows, and the
elaborator composes them per theory as megalodon.ml does.

usage: megalodon_upstream_tables.py MEGALODON_SRC_DIR OUTPUT [--check]
"""
import hashlib
import os
import re
import sys

PFG_TABLES = ["pfghfprim", "pfgegalprim", "pfgmizprim", "pfghoasprim", "pfgsetmmprim"]
PRESETS = ["preset_hf_index", "preset_mizar_index", "preset_hoas_index", "preset_setmm_index"]


def ocaml_type_to_sexpr(text):
    pos = 0

    def skip():
        nonlocal pos
        while pos < len(text) and text[pos] == " ":
            pos += 1

    def parse():
        nonlocal pos
        skip()
        if text.startswith("(", pos) and not text.startswith("(*", pos):
            pos += 1
            out = parse()
            skip()
            assert text[pos] == ")", text[pos:]
            pos += 1
            return out
        for word, out in (("Prop", "(PROP)"), ("Set", "(SET)")):
            if text.startswith(word, pos):
                pos += len(word)
                return out
        if text.startswith("Ar(", pos):
            pos += 3
            a = parse()
            skip()
            assert text[pos] == ",", text[pos:]
            pos += 1
            b = parse()
            skip()
            assert text[pos] == ")", text[pos:]
            pos += 1
            return "(AR %s %s)" % (a, b)
        raise ValueError("cannot parse type at %r" % text[pos:])

    out = parse()
    skip()
    assert pos == len(text), text
    return out


def extract_pfg(syntax):
    tables = {}
    for name in PFG_TABLES:
        row = re.compile(r'^Hashtbl\.add %s "([0-9a-f]{64})" (\d+);;\s*$' % name, re.M)
        tables[name] = [(h, int(n)) for h, n in row.findall(syntax)]
        if not tables[name]:
            raise ValueError("no rows for %s" % name)
    return tables


def extract_presets(megalodon):
    presets = {}
    for name in PRESETS:
        start = megalodon.index("let %s () =" % name)
        end = megalodon.index("\n\n", start)
        body = megalodon[start:end]
        tms = []
        knowns = []
        for line in body.splitlines():
            line = line.strip().rstrip(";")
            m = re.match(r'Hashtbl\.add indextms "([0-9a-f]{64})" (.*)$', line)
            if m:
                tms.append((m.group(1), ocaml_type_to_sexpr(m.group(2))))
                continue
            m = re.match(r'Hashtbl\.add indexknowns "([0-9a-f]{64})" \(\)$', line)
            if m:
                knowns.append(m.group(1))
        clears = "Hashtbl.clear indextms" in body
        presets[name] = (clears, tms, knowns)
    return presets


def extract_distinct(megalodon):
    """The named constants of the distinct tactic (megalodon.ml, SpecialTac
    "distinct"): the knowns and terms its proofs are built from."""
    start = megalodon.index('SpecialTac(x,[]) when x = "distinct"')
    end = megalodon.index('SpecialTac(x,[]) when x = "reflexivity"', start)
    body = megalodon[start:end]
    rows = re.findall(r'let (\w+) = "([0-9a-f]{64})" in', body)
    seen = {}
    for name, h in rows:
        if name in seen and seen[name] != h:
            raise ValueError("distinct constant %s has two values" % name)
        seen[name] = h
    if len(seen) < 70:
        raise ValueError("too few distinct constants: %d" % len(seen))
    return sorted(seen.items())


def render(pfg, presets, hashes, distinct):
    out = ["/* Generated by tools/megalodon_upstream_tables.py from Megalodon's",
           " * src/syntax.ml (SHA-256 %s)" % hashes[0],
           " * and src/megalodon.ml (SHA-256 %s)." % hashes[1],
           " * Do not edit. */", ""]
    for name in PFG_TABLES:
        out.append("static const MgUpstreamPrim mg_%s[] = {" % name)
        for h, n in pfg[name]:
            out.append('    {"%s", %du},' % (h, n))
        out.append("};")
        out.append("")
    for name in PRESETS:
        clears, tms, knowns = presets[name]
        out.append("/* %s%s */" % (name, ": clears the indexes first" if clears else ""))
        out.append("static const MgUpstreamIndexed mg_%s_tms[] = {" % name)
        for h, tp in tms:
            out.append('    {"%s", "%s"},' % (h, tp))
        if not tms:
            out.append("    {NULL, NULL},")
        out.append("};")
        out.append("static const char *const mg_%s_knowns[] = {" % name)
        for h in knowns:
            out.append('    "%s",' % h)
        if not knowns:
            out.append("    NULL,")
        out.append("};")
        out.append("#define MG_%s_TMS %du" % (name.upper(), len(tms)))
        out.append("#define MG_%s_KNOWNS %du" % (name.upper(), len(knowns)))
        out.append("#define MG_%s_CLEARS %s" % (name.upper(), "true" if clears else "false"))
        out.append("")
    out.append("/* megalodon.ml SpecialTac \"distinct\": its named constants */")
    out.append("static const MgUpstreamNamed mg_distinct_names[] = {")
    for name, h in distinct:
        out.append('    {"%s", "%s"},' % (name, h))
    out.append("};")
    out.append("")
    return "\n".join(out)


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    if len(args) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    syntax_bytes = open(os.path.join(args[0], "syntax.ml"), "rb").read()
    megalodon_bytes = open(os.path.join(args[0], "megalodon.ml"), "rb").read()
    megalodon_text = megalodon_bytes.decode("utf-8", "replace")
    text = render(extract_pfg(syntax_bytes.decode("utf-8", "replace")),
                  extract_presets(megalodon_text),
                  (hashlib.sha256(syntax_bytes).hexdigest(),
                   hashlib.sha256(megalodon_bytes).hexdigest()),
                  extract_distinct(megalodon_text))
    if "--check" in argv:
        current = open(args[1]).read()
        if current != text:
            print("%s is out of date" % args[1], file=sys.stderr)
            return 1
        print("%s is up to date" % args[1])
        return 0
    with open(args[1], "w") as f:
        f.write(text)
    print("wrote %s" % args[1])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
