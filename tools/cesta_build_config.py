#!/usr/bin/env python3
"""Emit the configured runtime header, updating its version from VERSION."""
import argparse
import json
import os
from pathlib import Path
import re
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--version-file', type=Path, required=True)
    parser.add_argument('--define', action='append', default=[])
    args = parser.parse_args()
    lines = ['/* autogenerated by Makefile; do not edit */']
    seen = set()
    for definition in args.define:
        name, sep, value = definition.partition('=')
        if not sep or not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', name) or name in seen or '\n' in value:
            parser.error(f'invalid or duplicate definition: {definition!r}')
        seen.add(name)
        if name == 'CETTA_VERSION_STRING':
            value = json.dumps(args.version_file.read_text().strip())
        lines.append(f'#define {name} {value}')
    if 'CETTA_VERSION_STRING' not in seen:
        parser.error('missing CETTA_VERSION_STRING')
    text = '\n'.join(lines) + '\n'
    if args.output.exists() and args.output.read_text() == text:
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=args.output.parent, prefix=args.output.name + '.', delete=False) as f:
        f.write(text)
        temporary = f.name
    os.replace(temporary, args.output)


if __name__ == '__main__':
    main()
