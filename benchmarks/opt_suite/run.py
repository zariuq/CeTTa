#!/usr/bin/env python3
"""Measure ordinary MeTTa programs against their original Opt MM2 tasks.

This compares applications, not CeTTa's MORK-backed MM2 front end. MORK's
execution timer and whole-process wall time are separate: its CLI serializes
the final store, while the MeTTa application publishes relation cardinalities.
Use --observe on a corpus generated with --observe to compare complete
projected result sets.

Every row records the measured job's whole-process wall time, user and system
CPU time and peak resident set size (from /usr/bin/time), MORK's own execution
time, and with --instructions the job's instructions:u (perf stat).
"""
import argparse
import collections
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "benchmarks/mam_families"))
from petta_corpus_manifest import alpha_canonicalize_atom_text

spec = importlib.util.spec_from_file_location("application_measure", ROOT / "benchmarks/mam_families/run.py")
measure = importlib.util.module_from_spec(spec)
spec.loader.exec_module(measure)

ENGINES = ("mork", "cetta", "swi")


def sha(path):
    with path.open("rb") as file:
        return hashlib.file_digest(file, "sha256").hexdigest()


def canonical(row, process=False):
    if process:
        if row.startswith("(petri "):
            row = row[7:-1]
        # Only the constructor-only process language generated by workloads.py.
        for old, new in (("!", "send"), ("?", "recv"), ("|", "par")):
            row = re.sub(r"\(" + re.escape(old) + r"(?=\s|\))", "(" + new, row)
    return alpha_canonicalize_atom_text(row)


def mork_observation(path, heads, complete):
    counts = collections.Counter()
    terms = set()
    with path.open() as file:
        for line in file:
            found = re.match(r"\(([^\s()]+)", line)
            if found and found[1] in heads:
                counts[found[1]] += 1
                if complete:
                    terms.add(canonical(line.strip(), "petri" in heads))
    return [counts[head] for head in heads], terms


def metta_observation(path, complete, process):
    numbers, terms = [], set()
    for line in path.read_text().splitlines():
        if re.fullmatch(r"\d+", line.strip()):
            numbers.append(int(line))
        if complete and line.startswith("(OBSERVED ") and line.endswith(")"):
            terms.add(canonical(line[10:-1], process))
    return numbers, terms


def limited(command, unlimited_stack, address_kib):
    """Apply only the resource limits that were requested."""
    limits = []
    if unlimited_stack:
        limits.append("--stack=unlimited")
    if address_kib:
        limits.append(f"--as={address_kib * 1024}")
    return ["prlimit", *limits, "--", *command] if limits else command


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("corpus", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--cetta", type=Path, required=True)
    parser.add_argument("--mork", type=Path, required=True)
    parser.add_argument("--petta-root", type=Path)
    parser.add_argument("--engines", help="comma-separated subset of mork,cetta,swi; "
                        "default mork,cetta, plus swi when --petta-root is given")
    parser.add_argument("--trials", type=int, default=3)
    parser.add_argument("--timeout", type=float, default=180)
    parser.add_argument("--budget", type=float, default=1800)
    parser.add_argument("--cpu", type=int)
    parser.add_argument("--case", action="append")
    parser.add_argument("--observe", action="store_true")
    parser.add_argument("--reference-only", action="store_true", help="refresh only MORK measurements")
    parser.add_argument("--instructions", action="store_true", help="also count instructions:u with perf stat")
    parser.add_argument("--unlimited-stack", action="store_true",
                        help="give every engine an unlimited stack; MORK recurses over term depth")
    parser.add_argument("--address-limit-kib", type=int,
                        help="address-space limit for the MeTTa engines; MORK reserves "
                             "large virtual ranges and is not limited")
    args = parser.parse_args()
    corpus, output = args.corpus.resolve(), args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((corpus / "manifest.json").read_text())
    if args.case:
        manifest = [case for case in manifest if case["case"] in args.case]
    if not manifest or args.trials < 1 or args.timeout <= 0 or args.budget <= 0:
        parser.error("nonempty selection and positive trials/time budgets required")
    if args.reference_only:
        engines = ["mork"]
    elif args.engines:
        engines = [engine.strip() for engine in args.engines.split(",") if engine.strip()]
    else:
        engines = ["mork", "cetta"] + (["swi"] if args.petta_root else [])
    if not engines or any(engine not in ENGINES for engine in engines) or "mork" not in engines:
        parser.error("engines must be a subset of mork,cetta,swi that includes the mork reference")
    if "swi" in engines and not args.petta_root:
        parser.error("--petta-root is required for swi")
    identities = {"cetta": sha(args.cetta), "mork": sha(args.mork)}
    environment = dict(os.environ, RAYON_NUM_THREADS="1")
    rows, failed = [], False
    started = time.monotonic()
    results = output / "results.json"
    for case in manifest:
        name, heads = case["case"], case["heads"]
        for item in case["files"].values():
            if sha(corpus / item["path"]) != item["sha256"]:
                raise ValueError("changed workload: " + name)
        complete = args.observe
        if complete and case["observer"] != "complete projected set":
            parser.error("--observe requires generator --observe")
        reference = None
        dead = set()
        for trial in range(args.trials):
            # Reference first on the first trial, then alternate complete jobs.
            for engine in engines if trial % 2 == 0 else reversed(engines):
                if engine in dead:
                    continue
                remaining = args.budget - (time.monotonic() - started)
                if remaining <= 0:
                    raise RuntimeError("measurement budget exhausted; partial rows retained")
                stem = output / "runs" / name / f"{engine}-{trial}"
                store = stem.with_suffix(".mm2")
                if engine == "mork":
                    command = [str(args.mork.resolve()), "run", str(corpus / case["files"]["mm2"]["path"]), str(store), "--instrumentation", "0"]
                    command = limited(command, args.unlimited_stack, None)
                    cwd = corpus
                elif engine == "cetta":
                    command = [str(args.cetta.resolve()), "--lang", "petta", "--profile", "extended", str(corpus / case["files"]["metta"]["path"])]
                    command = limited(command, args.unlimited_stack, args.address_limit_kib)
                    cwd = corpus
                else:
                    command = ["sh", str(args.petta_root.resolve() / "run.sh"), str(corpus / case["files"]["swi.metta"]["path"]), "--silent"]
                    command = limited(command, args.unlimited_stack, args.address_limit_kib)
                    cwd = args.petta_root.resolve()
                measured = measure.paired_measure(command, cwd, environment, stem,
                                                  min(args.timeout, remaining), args.cpu,
                                                  args.instructions)
                passed = measured["rc"] == 0 and not measured["timed_out"]
                counts, terms = [], set()
                if passed:
                    if engine == "mork":
                        counts, terms = mork_observation(store, heads, complete)
                        if reference is None:
                            reference = counts, terms
                    else:
                        counts, terms = metta_observation(Path(measured["stdout_file"]), complete, "petri" in heads)
                        if case["family"] == "odd_even_sort" and (len(counts) != 2 or counts[0] != 0):
                            passed = False
                        counts = counts[-len(heads):]
                    passed = passed and reference is not None and counts == reference[0]
                    if complete:
                        passed = passed and terms == reference[1]
                status = ("pass" if passed else "timeout" if measured["timed_out"] else
                          "exit-failure" if measured["rc"] else
                          "reference-unavailable" if reference is None else "different-observation")
                user, system = measured["native_user"], measured["native_system"]
                row = {"case": name, "family": case["family"], "arguments": case["arguments"],
                       "engine": engine, "trial": trial, "status": status, "counts": counts,
                       "reference_counts": reference[0] if reference else None,
                       "complete_set_compared": complete, "observed_distinct_rows": len(terms) if complete else None,
                       "cpu": None if user is None or system is None else user + system,
                       "user": user, "system": system, "native_wall": measured["native_wall"],
                       "instructions": measured["instructions"], "command": measured["command"],
                       **{key: measured[key] for key in ("wall", "rss_kib", "rc", "timed_out")}}
                if engine == "mork":
                    text = Path(measured["stdout_file"]).read_text()
                    match = re.search(r"executing (\d+) steps took (\d+) ms", text)
                    row["execution_ms"] = int(match[2]) if match else None
                    row["steps"] = int(match[1]) if match else None
                    if store.exists() and not complete:
                        store.unlink()  # Own reproducible, potentially large dump.
                rows.append(row)
                results.write_text(json.dumps(dict(identities=identities, trials=args.trials,
                    timeout_seconds=args.timeout, cpu=args.cpu, engines=engines,
                    unlimited_stack=args.unlimited_stack, rows=rows), indent=2) + "\n")
                cpu = "-" if row["cpu"] is None else f"{row['cpu']:.3f}s cpu"
                print(f"{name}: {engine} trial {trial + 1}: {status}, {measured['wall']:.3f}s wall, {cpu}, "
                      f"{measured['rss_kib']} KiB, counts={counts}", flush=True)
                if not passed:
                    dead.add(engine)
                    failed = True
        for item in case["files"].values():
            if sha(corpus / item["path"]) != item["sha256"]:
                raise ValueError("workload changed while measuring: " + name)
    if identities != {"cetta": sha(args.cetta), "mork": sha(args.mork)}:
        raise ValueError("executable changed during measurement")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
