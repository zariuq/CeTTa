#!/usr/bin/env python3
"""Run MAM family cases against independently generated answer oracles.

Paired adapters generated by panel.py:
    run.py --paired CASEDIR OUTDIR CETTA_BINARY [case ...]
           --engines cetta-petta,swi,cetta-he,he,jetta,mork
           --he-bin BINARY --java JAVA --jetta-jar JAR --mork-bin BINARY

Only request the engines to run. HE transport brackets are normalized without
losing duplicate occurrences. Native JeTTa compilation is timed separately;
native MORK projects explicitly declared result heads from its final store.
ACT attachment requires the separately generated preparation program.

Original CLI: run.py CASEDIR OUTDIR CETTA_BINARY [--engines cetta,swi] [--baseline BINARY]
              [--trials N] [case ...]

Engines: `cetta` (the binary as given), `canonical` (the same binary with every
compiled route off: a transition budget, however large, sends every call through
canonical search), `baseline` (another CeTTa binary) and `swi` (SWI-PeTTa).

Full process measurement (perf stat instructions:u, cycles:u; /usr/bin/time wall,
user, peak RSS).  An engine's answers are its stdout lines after the case's header
lines; they must equal <case>.expected exactly (order and multiplicity).
"""
import argparse, hashlib, json, os, resource, shlex, signal, subprocess, sys, threading, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PETTA = ROOT.parent/'PeTTa'
sys.path.insert(0,str(ROOT/'scripts'))
from petta_corpus_manifest import alpha_canonicalize_atom_text

def measure(label, cmd, cwd, out, timeout, env=None):
    perf, tm, so = out/f'{label}.perf', out/f'{label}.time', out/f'{label}.out'
    full = ['perf', 'stat', '-x', ',', '-e', 'instructions:u,cycles:u', '-o', str(perf), '--',
            '/usr/bin/time', '-f', '%e %U %S %M', '-o', str(tm), *cmd]
    try:
        with so.open('wb') as o, (out/f'{label}.err').open('wb') as e:
            rc = subprocess.run(full, cwd=cwd, stdout=o, stderr=e, timeout=timeout,
                                env=env).returncode
    except subprocess.TimeoutExpired:
        return dict(rc='timeout')
    wall, user, _sys, rss = tm.read_text().split()[-4:]
    counts = {}
    for l in perf.read_text().splitlines():
        f = l.split(',')
        if len(f) > 2 and f[0].isdigit(): counts[f[2]] = int(f[0])
    return dict(rc=rc, wall=float(wall), user=float(user), rss_kib=int(rss),
                instructions=counts.get('instructions:u'), cycles=counts.get('cycles:u'),
                stdout=so.read_text(errors='replace'))

def main():
    args = sys.argv[1:]
    def opt(name, default):
        if name in args:
            i = args.index(name); v = args[i+1]; del args[i:i+2]; return v
        return default
    engines = opt('--engines', 'cetta,swi').split(',')
    trials = int(opt('--trials', '1'))
    baseline = opt('--baseline', None)
    timeout = int(opt('--timeout', '600'))
    cases_dir, out, cetta = Path(args[0]), Path(args[1]), Path(args[2]).resolve()
    out.mkdir(parents=True, exist_ok=True)
    manifest = {r['case']: r for r in json.loads((cases_dir/'manifest.json').read_text())}
    names = args[3:] or list(manifest)
    rows = []
    for case in names:
        m = manifest[case]; src = (cases_dir/f'{case}.metta').resolve()
        expected = (cases_dir/f'{case}.expected').read_text().splitlines()
        for t in range(trials):
            for eng in (engines if t % 2 == 0 else list(reversed(engines))):
                env = None
                if eng == 'swi':
                    cmd, cwd = ['./run.sh', str(src), '--silent'], PETTA
                else:
                    binary = Path(baseline).resolve() if eng == 'baseline' else cetta
                    cmd, cwd = [str(binary), '--lang', 'petta', str(src)], ROOT
                    if eng == 'canonical':
                        env = dict(os.environ,
                                   CETTA_PETTA_MACHINE_TRANSITION_LIMIT='18446744073709551615')
                r = measure(f'{case}-{eng}-{t}', cmd, cwd, out, timeout, env)
                lines = r.pop('stdout', '').splitlines()
                got = lines[m['header_lines']:]
                r.update(case=case, engine=eng, trial=t, correct=(r['rc'] == 0 and got == expected),
                         answers=len(got))
                rows.append(r)
                print(f"{case:40s} {eng:9s} t{t} ok={r['correct']!s:5s} "
                      f"{(r.get('instructions') or 0)/1e9:9.3f}G {r.get('wall', 0):7.2f}s "
                      f"{r.get('rss_kib', 0)/1024:8.1f}MB rc={r['rc']}", flush=True)
    (out/'results.json').write_text(json.dumps(dict(
        cetta=str(cetta), cetta_sha256=hashlib.sha256(cetta.read_bytes()).hexdigest(),
        baseline=baseline,
        rows=rows), indent=1) + '\n')

def answer_atoms(stdout: str, grouped: bool | str) -> list[str]:
    """Remove transport brackets while retaining answer order and duplicates.

    Commas inside terms and quoted strings are data. Only top-level commas in
    HE's result brackets separate answer occurrences. Unexpected unbalanced
    framing is a failed observation, never an empty answer.
    """
    atoms = []
    for raw in stdout.splitlines():
        line=raw.strip()
        if not line:
            continue
        if not grouped or (grouped=='auto' and not line.startswith('[')):
            atoms.append(alpha_canonicalize_atom_text(line))
            continue
        if not (line.startswith('[') and line.endswith(']')):
            raise ValueError(f'unexpected result framing: {line[:100]!r}')
        content=line[1:-1]
        if not content.strip():
            continue
        start=0
        depth=0
        quoted=False
        escaped=False
        for i,c in enumerate(content):
            if quoted:
                if escaped: escaped=False
                elif c=='\\': escaped=True
                elif c=='"': quoted=False
            elif c=='"': quoted=True
            elif c=='(': depth+=1
            elif c==')':
                depth-=1
                if depth<0: raise ValueError('unbalanced result term')
            elif c==',' and depth==0:
                atom=content[start:i].strip()
                if not atom: raise ValueError('empty result occurrence')
                atoms.append(alpha_canonicalize_atom_text(atom))
                start=i+1
        if depth or quoted:
            raise ValueError('incomplete result term')
        atom=content[start:].strip()
        if not atom: raise ValueError('empty trailing result occurrence')
        atoms.append(alpha_canonicalize_atom_text(atom))
    return atoms


def paired_measure(cmd, cwd, env, stem, timeout, cpu, instructions):
    """Reap the complete job; kill its process group on timeout."""
    stem.parent.mkdir(parents=True,exist_ok=True)
    so=stem.with_suffix('.stdout')
    se=stem.with_suffix('.stderr')
    perf=stem.with_suffix('.perf')
    if instructions:
        cmd=['perf','stat','-x',',','-e','instructions:u,cycles:u','-o',str(perf),'--',*cmd]
    def prepare():
        if cpu is not None: os.sched_setaffinity(0,{cpu})
    started=time.perf_counter()
    with so.open('wb') as stdout, se.open('wb') as stderr:
        p=subprocess.Popen(cmd,cwd=cwd,env=env,stdin=subprocess.DEVNULL,
                           stdout=stdout,stderr=stderr,start_new_session=True,
                           preexec_fn=prepare if cpu is not None else None)
        expired=[]
        def cancel():
            expired.append(True)
            try: os.killpg(p.pid,signal.SIGKILL)
            except ProcessLookupError: pass
        timer=threading.Timer(timeout,cancel)
        timer.start()
        _,status,usage=os.wait4(p.pid,0)
        timer.cancel()
        p.returncode=os.waitstatus_to_exitcode(status)
    counts={}
    if instructions and perf.exists():
        for line in perf.read_text().splitlines():
            fields=line.split(',')
            if len(fields)>2 and fields[0].isdigit(): counts[fields[2]]=int(fields[0])
    return dict(rc=p.returncode,timed_out=bool(expired),wall=time.perf_counter()-started,
                user=usage.ru_utime,system=usage.ru_stime,rss_kib=usage.ru_maxrss,
                instructions=counts.get('instructions:u'),cycles=counts.get('cycles:u'),
                stdout_sha256=hashlib.sha256(so.read_bytes()).hexdigest(),
                stdout_file=str(so),stderr_file=str(se),command=cmd)


def paired_main():
    from collections import Counter
    from uuid import uuid4
    ap=argparse.ArgumentParser(description='Correctness-gated paired MAM workload runner')
    ap.add_argument('--paired',action='store_true')
    ap.add_argument('cases_dir',type=Path)
    ap.add_argument('out',type=Path)
    ap.add_argument('cetta',type=Path)
    ap.add_argument('cases',nargs='*')
    ap.add_argument('--engines',default='cetta-petta,swi,cetta-he,he')
    ap.add_argument('--petta-root',type=Path,default=PETTA)
    ap.add_argument('--he-bin',type=Path)
    ap.add_argument('--java',default='java')
    ap.add_argument('--java-args',default='')
    ap.add_argument('--jetta-jar',type=Path)
    ap.add_argument('--mork-bin',type=Path)
    ap.add_argument('--trials',type=int,default=3)
    ap.add_argument('--timeout',type=float,default=60)
    ap.add_argument('--cpu',type=int)
    ap.add_argument('--instructions',action='store_true')
    ap.add_argument('--engine-env',action='append',default=[],metavar='ENGINE:KEY=VALUE')
    args=ap.parse_args()
    if args.trials<1 or args.timeout<=0: ap.error('trials and timeout must be positive')
    cases=args.cases_dir.resolve()
    out=args.out.resolve()
    out.mkdir(parents=True,exist_ok=True)
    manifest_bytes=(cases/'manifest.json').read_bytes()
    manifest={m['case']:m for m in json.loads(manifest_bytes)}
    (out/'cases-manifest.json').write_bytes(manifest_bytes)
    names=args.cases or list(manifest)
    engines=args.engines.split(',')
    known={'cetta-petta','swi','cetta-he','he','jetta','cetta-mork','mork'}
    if set(engines)-known: ap.error('unknown engines: '+', '.join(sorted(set(engines)-known)))
    configured={e:{} for e in engines}
    for item in args.engine_env:
        eng,assignment=item.split(':',1)
        key,value=assignment.split('=',1)
        if eng not in configured: ap.error(f'env configured for absent engine {eng}')
        configured[eng][key]=value
    def sha_file(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
    identities={'cetta':sha_file(args.cetta),'manifest':hashlib.sha256(manifest_bytes).hexdigest()}
    if args.he_bin: identities['he']=sha_file(args.he_bin)
    if args.jetta_jar: identities['jetta']=sha_file(args.jetta_jar)
    if args.mork_bin: identities['mork']=sha_file(args.mork_bin)
    run_identity=dict(binaries=identities,engine_env=configured,cpu=args.cpu,
                      trials=args.trials,timeout=args.timeout,instructions=args.instructions)
    (out/'identity.json').write_text(json.dumps(run_identity,indent=2)+'\n')
    rows=[]
    failures=False
    with (out/'runs.jsonl').open('w') as log:
        def record(row):
            rows.append(row)
            log.write(json.dumps(row,ensure_ascii=False)+'\n'); log.flush()
        for name in names:
            m=manifest[name]
            expected_path=cases/m['expected']
            if sha_file(expected_path)!=m['expected_sha256']:
                raise ValueError(f'changed oracle: {name}')
            expected=[alpha_canonicalize_atom_text(s) for s in expected_path.read_text().splitlines()]
            ready={}
            for eng in engines:
                dialect={'swi':'petta','he':'he','cetta-he':'he','cetta-petta':'petta',
                         'jetta':'jetta','cetta-mork':'cetta-mork','mork':'mork'}.get(eng)
                if dialect not in m['dialects']:
                    record(dict(case=name,engine=eng,phase='selection',status='not-applicable',correct=None))
                    continue
                variant=m['dialects'][dialect]
                src=cases/variant['source']
                if sha_file(src)!=variant['sha256']: raise ValueError(f'changed source: {src}')
                dependencies={str((cases/dep).resolve()):sha_file(cases/dep)
                              for dep in variant.get('dependencies',[])}
                env=dict(os.environ,**configured[eng])
                if eng in {'cetta-he','cetta-petta','cetta-mork'}:
                    lang='petta' if eng=='cetta-petta' else 'he'
                    cmd=[str(args.cetta.resolve()),'--lang',lang]
                    if eng=='cetta-mork': cmd+=['--quiet']
                    cmd+=[str(src)]
                elif eng=='swi': cmd=['sh',str(args.petta_root.resolve()/'run.sh'),str(src),'--silent']
                elif eng=='he':
                    if not args.he_bin: ap.error('--he-bin required for he')
                    cmd=[str(args.he_bin.resolve()),str(src)]
                elif eng=='mork':
                    if not args.mork_bin: ap.error('--mork-bin required for mork')
                    if m['contract']!='occurrence-bag' or not m['params'].get('projection_heads'):
                        raise ValueError('native MORK requires an explicit bag projection')
                    cmd=[str(args.mork_bin.resolve()),'run',str(src),'--steps',str(len(m['params']['projection_heads'])),
                         '--instrumentation','0','{store-output}']
                elif eng=='jetta':
                    if not args.jetta_jar: ap.error('--jetta-jar required for jetta')
                    jar=str(args.jetta_jar.resolve())
                    java=[args.java,*shlex.split(args.java_args)]
                    dest=out/'classes'/name/uuid4().hex
                    dest.mkdir(parents=True,exist_ok=True)
                    compile_run=paired_measure([*java,'-jar',jar,str(src),'-d',str(dest)],
                                              src.parent,env,out/'compile'/name,
                                              args.timeout,args.cpu,False)
                    ok=compile_run['rc']==0 and not compile_run['timed_out'] and (dest/f'{src.stem}.class').exists()
                    record(dict(case=name,engine=eng,phase='compile',status='compiled' if ok else 'compile-failed',correct=None,**compile_run))
                    if not ok:
                        failures=True
                        print(f'{name} {eng}: compile-failed',flush=True)
                        continue
                    cmd=[*java,f'-Djetta.dataDir={dest}','-cp',f'{dest}:{jar}',src.stem]
                else: ap.error(f'unknown engine {eng}')
                alternate=expected
                if 'expected' in variant:
                    ep=cases/variant['expected']
                    if sha_file(ep)!=variant['expected_sha256']: raise ValueError(f'changed variant oracle: {ep}')
                    alternate=[alpha_canonicalize_atom_text(s) for s in ep.read_text().splitlines()]
                contract=variant.get('contract',m['contract'])
                if contract not in {'exact-stream','occurrence-bag'}:
                    raise ValueError('unknown observation contract: '+contract)
                ready[eng]=(cmd,env,'auto' if eng=='jetta' else eng in {'he','cetta-he','cetta-mork'},variant.get('preamble',[]),alternate,contract,dependencies,
                            variant['sha256'],variant.get('expected_sha256',m['expected_sha256']))
            failed_engines=set()
            for trial in range(args.trials):
                for eng in engines if trial%2==0 else reversed(engines):
                    if eng not in ready or eng in failed_engines: continue
                    cmd,env,grouped,preamble,oracle,contract,dependencies,source_sha,oracle_sha=ready[eng]
                    stem=out/'runs'/name/f'{eng}-{trial}'
                    if eng=='mork':
                        store=stem.with_suffix('.store')
                        cmd=[str(store) if s=='{store-output}' else s for s in cmd]
                    rr=paired_measure(cmd,cases,env,stem,
                                      args.timeout,args.cpu,args.instructions)
                    valid=rr['rc']==0 and not rr['timed_out']
                    if any(sha_file(dep)!=digest for dep,digest in dependencies.items()):
                        raise ValueError('changed runtime dependency: '+name)
                    status='timeout' if rr['timed_out'] else ('exit-failure' if rr['rc'] else 'wrong-answer')
                    try:
                        observation=Path(rr['stdout_file']).read_text()
                        if eng=='mork':
                            rr['store_file']=str(store)
                            rr['store_sha256']=sha_file(store)
                            heads=m['params']['projection_heads']
                            observation='\n'.join(s for s in store.read_text().splitlines()
                                                  if any(s.startswith('('+h+' ') for h in heads))
                        got=answer_atoms(observation,grouped)
                        prefix=[alpha_canonicalize_atom_text(s) for s in preamble]
                        if got[:len(prefix)]!=prefix:
                            raise ValueError('setup observation differs')
                        got=got[len(prefix):]
                        if any(s.startswith('(Error ') for s in got): valid=False
                        correct=valid and (Counter(got)==Counter(oracle) if contract=='occurrence-bag' else got==oracle)
                    except (ValueError,UnicodeError,OSError) as err:
                        got=[]; correct=False; rr['observation_error']=str(err)
                        if valid: status='invalid-output'
                    if correct: status='pass'
                    record(dict(case=name,engine=eng,trial=trial,phase='run',status=status,
                                correct=correct,answers=len(got),contract=contract,
                                dependencies=dependencies,source_sha256=source_sha,
                                oracle_sha256=oracle_sha,**rr))
                    print(f'{name:34s} {eng:12s} {status:14s} {rr["wall"]:.6f}s {rr["rss_kib"]}KiB',flush=True)
                    if not correct:
                        failures=True
                        # Do not repeat an unchanged timeout, crash or wrong answer.
                        failed_engines.add(eng)
    assert sha_file(args.cetta)==identities['cetta']
    if args.he_bin: assert sha_file(args.he_bin)==identities['he']
    if args.jetta_jar: assert sha_file(args.jetta_jar)==identities['jetta']
    if args.mork_bin: assert sha_file(args.mork_bin)==identities['mork']
    (out/'results.json').write_text(json.dumps(dict(identity=run_identity,rows=rows),indent=2)+'\n')
    if not any(row['phase']=='run' for row in rows):
        print('No engine/case pair executed.',file=sys.stderr)
        failures=True
    if failures: raise SystemExit(1)


if __name__ == '__main__':
    # Paired manifests use the same independent oracle format as the original
    # MAM suite. Keep the original CLI available for its existing callers.
    if '--paired' in sys.argv:
        paired_main()
    else:
        main()
